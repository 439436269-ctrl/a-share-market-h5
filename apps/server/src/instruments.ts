/**
 * 标的主数据（Instrument Master）。
 *
 * 全部用真实 A 股代码/名称，因为行情 Demo 一旦用 "TEST001" 这种假数据，
 * 面试官一眼就知道你没有对着真实业务做过。
 *
 * 注意 000001 这个例子：它是**上证指数**（000001.SH），
 * 也是**平安银行**（000001.SZ）。所以标的唯一键必须带市场后缀 ——
 * 这是行情系统里最经典的一个坑，也是 symbol 而非 code 做主键的原因。
 */
import type { Board, Instrument, MarketId } from '@stock/market-core';

function ins(
  code: string,
  name: string,
  market: MarketId,
  board: Board,
  prevClose: number,
  floatShares: number,
): Instrument {
  const limitPct =
    board === 'index' ? 0 : board === 'gem' || board === 'star' ? 0.2 : board === 'bj' ? 0.3 : 0.1;
  return {
    symbol: `${code}.${market}`,
    code,
    name,
    market,
    board,
    limitPct,
    prevClose,
    floatShares,
  };
}

